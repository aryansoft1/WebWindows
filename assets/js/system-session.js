  function operationLanguage() {
    var language = "zh";
    try {
      var i18n = window.WebWindowsI18n;
      language = String((i18n && typeof i18n.getLanguage === "function" && i18n.getLanguage())
        || (window.localStorage && window.localStorage.getItem("lang")) || "zh").toLowerCase();
    } catch (_) { /* Keep Simplified Chinese when storage or the i18n bridge is unavailable. */ }
    if (language === "jp" || language.indexOf("ja") === 0) return "jp";
    if (language === "tw" || language.indexOf("zh-tw") === 0 || language.indexOf("zh-hk") === 0
      || language.indexOf("zh-mo") === 0 || language.indexOf("hant") !== -1) return "tw";
    if (language.indexOf("en") === 0) return "en";
    return "zh";
  }

  function localizeOperationText(text) {
    var language = operationLanguage();
    if (language === "zh") return text;
    var translations = OPERATION_DIALOG_TRANSLATIONS[language];
    if (translations && Object.prototype.hasOwnProperty.call(translations, text)) return translations[text];
    var i18n = window.WebWindowsI18n;
    if (i18n && typeof i18n.translate === "function") {
      try { return i18n.translate(text, language); } catch (_) { /* Use the source text as a safe fallback. */ }
    }
    return text;
  }

  function isTopLevelTrustedDocument() {
    if (window.top !== window.self) return false;
    return location.protocol === "https:" || location.hostname === "localhost" || location.hostname === "127.0.0.1";
  }

  function nativeBridge() {
    var bridge = window[NATIVE_BRIDGE_NAME];
    if (!isTopLevelTrustedDocument() || !bridge || bridge.version !== 1) return null;
    if (typeof bridge.getCapabilities !== "function" || typeof bridge.requestOperation !== "function") return null;
    return bridge;
  }

  function readNativeCapabilities() {
    var bridge = nativeBridge();
    if (!bridge) return {};
    try {
      var value = bridge.getCapabilities();
      if (typeof value === "string") value = JSON.parse(value);
      if (!value || typeof value !== "object") return {};
      var result = {};
      DEVICE_ACTIONS.forEach(function (action) {
        result[action] = value[action] === true;
      });
      return result;
    } catch (error) {
      console.warn("[DeviceOperations] 无法读取原生能力，使用会话级替代行为。", error);
      return {};
    }
  }

  function getCapabilities() {
    var native = readNativeCapabilities();
    var result = {};
    ACTIONS.forEach(function (action) {
      var isNative = native[action] === true;
      result[action] = {
        available: true,
        level: isNative ? "native" : "session",
        label: localizeOperationText(isNative ? NATIVE_LABELS[action] : SESSION_PRESENTATION[action].label)
      };
    });
    return result;
  }

