import assert from "node:assert/strict";
import fs from "node:fs/promises";

const read = async (relative) => fs.readFile(new URL(`../${relative}`, import.meta.url), "utf8");
const page = await read("developer.html");
const script = await read("assets/js/developer-center.js");
const style = await read("assets/css/developer-center.css");
const release = JSON.parse(await read("data/developer/content-v1.json"));
const manifest = JSON.parse(await read("developer-samples/hello-webwindows/manifest.json"));
const sample = await read("developer-samples/hello-webwindows/index.html");
const admin = await read("SystemManager/developer-platform.html");
const archive = await fs.readFile(new URL("../developer-samples/hello-webwindows.zip", import.meta.url));
const archiveText = archive.toString("latin1");

assert.match(page, /第一次开发，按这条路线走/);
assert.match(page, /Developer API v1/);
assert.match(page, /X-WebWindows-Developer-Request: v1/);
assert.match(page, /X-WebWindows-Developer-Key/);
assert.match(page, /LOGIN_REQUIRED/);
assert.match(page, /SUBMISSION_RATE_LIMIT/);
assert.match(page, /Manifest 参考/);
assert.match(page, /hello-webwindows\.zip/);
assert.match(page, /文档、后台与未来社区的边界/);
assert.match(page, /assets\/icons\/logo_large\.png/);
assert.match(page, /id="returnWebWindows"/);
assert.match(page, /data-save-sample/);
assert.doesNotMatch(page, /hello-webwindows\.zip" download/);
assert.match(script, /data\/developer\/content-v1\.json/);
assert.match(script, /release\.status !== "published"/);
assert.match(script, /data-copy-target/);
assert.match(script, /window\.parent\.closeWindow\("developer-center"\)/);
assert.match(script, /WebWindows\.fileDialog\.save/);
assert.match(script, /WebWindows\.fileDialog\.write/);
assert.match(script, /purpose: "developer-sample-save"/);
assert.doesNotMatch(script, /createElement\("a"\).*download/s);
assert.match(style, /\.side-nav/);
assert.match(style, /\.manifest-layout/);
assert.equal(release.schemaVersion, 1);
assert.equal(release.status, "published");
assert.equal(release.apiVersion, "v1");
assert.ok(release.documents.every((item) => item.status === "published"));
assert.ok(release.publishingBoundary.adminBackend.includes("versioning"));
assert.ok(release.publishingBoundary.adminBackend.includes("unpublish"));
assert.equal(release.samples[0].saveMode, "private-cloud");
assert.equal(manifest.id, "com.example.hello");
assert.equal(manifest.entry, "index.html");
assert.equal(manifest.icon, "icon.svg");
assert.equal(manifest.install.defaultState, "available");
assert.equal(manifest.window.mode, "iframe");
assert.doesNotMatch(sample, /fetch\s*\(|XMLHttpRequest|type=["']module["']/i);
assert.match(sample, /Hello WebWindows/);
assert.match(archiveText, /manifest\.json/);
assert.match(archiveText, /index\.html/);
assert.match(archiveText, /icon\.svg/);
assert.match(admin, /开发者内容发布/);
assert.match(admin, /content-v1\.json/);
assert.match(admin, /草稿、版本、发布与下线/);

console.log("developer center documentation smoke test passed");
