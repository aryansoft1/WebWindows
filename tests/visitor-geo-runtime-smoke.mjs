import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync, rmSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

/*
 * 真正**执行** inc/visitor-geo.asp 的运行门禁。
 *
 * 2026-09-26 连续三次线上事故都出在这段 VBScript 上，而静态检查与 cscript 编译
 * 期检查全都测不到：
 *   ① 注释里的 ASP 定界符提前结束脚本块 → 源码被回显；
 *   ② Server.MapPath 相对路径在 include 里解析到 /inc/ → 配置永远读不到；
 *   ③ GeoSafeAddress 白名单漏掉小数点 → 每个 IPv4 都被判非法，地区解析从未发起。
 * 三次都只能靠线上试探发现，代价极高。因此这里用 Windows Script Host 真正跑一遍
 * 逻辑：把 include 的代码抽出来，配上 Server / Request 桩对象执行，再对结果断言。
 *
 * 两处必要的机械变换（只改名字，不改逻辑）：
 *   Application(key)            → AppGet(key)      （VBScript 类无法实现默认成员）
 *   Application(key) = value    → AppSet key, value
 */
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const includePath = path.join(root, "inc/visitor-geo.asp");
const raw = readFileSync(includePath, "utf8");

assert.ok(!/^\s*<%@/.test(raw), "the include must not carry a Language directive");
let code = raw.replace(/^<%/, "").replace(/%>\s*$/, "");
// Application(...) 的机械变换：参数里可能有字符串拼接（Application("k_" & address)），
// 也可能有一层嵌套（Application(GeoDayKey("x"))），所以不能只匹配标识符。
const appArg = "((?:[^()]|\\([^()]*\\))*)";
code = code.replace(new RegExp(`Application\\(${appArg}\\)\\s*=\\s*`, "g"), "AppSet $1, ");
code = code.replace(new RegExp(`Application\\(${appArg}\\)`, "g"), "AppGet($1)");
assert.ok(!/\bApplication\(/.test(code), "every Application reference must be transformable");

/*
 * 整行注释剥离后再执行，然后分两步处理非 ASCII：
 *   1) 守卫：**代码部分**（剥掉字符串字面量之后）必须纯 ASCII。中文只允许出现在
 *      注释和字符串字面量里 —— 否则 cscript 会按 ANSI 读成乱码，逻辑虽能跑但输出
 *      无法断言，而这类问题在生产上表现为「界面显示乱码」而不是报错。
 *   2) 交给 cscript 前把剩余非 ASCII 字符替换成 '?'：本机 cscript 不接受
 *      UTF-16LE+BOM（会报莫名的「语句未结束」），项目现有的
 *      tests/classic-asp-syntax-smoke.mjs 正是用 UTF-8 + CRLF 跑 cscript 的。
 *      因此断言不能依赖中文字面量的具体内容。
 */
code = code.split(/\r?\n/).filter((line) => !line.trim().startsWith("'")).join("\n");
const codeWithoutStrings = code.replace(/"(?:[^"]|"")*"/g, '""');
const strayNonAscii = codeWithoutStrings.match(/[^\x00-\x7F]/g);
assert.equal(strayNonAscii, null,
  `non-ASCII text must stay inside comments and string literals, found in code: ${(strayNonAscii || []).join("")}`);
const asciiCode = code.replace(/[^\x00-\x7F]/g, "?");

/*
 * 共享模块依赖调用方页面里的 Cut / ServerGeo 两个小工具（它们定义在
 * api/visitor-analytics.asp 而不是 include 里）。这里**从真实文件里抽取**它们的
 * 函数体，而不是手抄一份 —— 手抄会漂移，抽取则保证测的就是线上那一份。
 */
const collectorSource = readFileSync(path.join(root, "api/visitor-analytics.asp"), "utf8");
const helpers = ["Cut", "ServerGeo"].map((name) => {
  const match = new RegExp(`^Function ${name}\\([^\\n]*\\)[\\s\\S]*?^End Function$`, "m")
    .exec(collectorSource);
  assert.ok(match, `api/visitor-analytics.asp must still define Function ${name}`);
  return match[0];
}).join("\n\n");

const scratch = mkdtempSync(path.join(os.tmpdir(), "ww-geo-runtime-"));
const configPath = path.join(scratch, "visitor-analytics.config.asp");
writeFileSync(configPath, 'geoApiBase = "https://ipwho.is/{IP}?lang=zh-CN"\ngeoApiKey = ""\ngeoDailyCap = 800\n', "utf8");

// 故意用一个不可路由的端点：这样断言「是否真的发起了 HTTP」是确定的（必然超时），
// 而不是依赖外网可达性。
/*
 * 桩对象与断言体有两处**刻意的写法约束**（都是被本机 cscript 逼出来的，已实测）：
 *   1) 不能用 `Dim x As <类型>` / `Dim x As New <Class>` —— 本机 VBScript 引擎
 *      （vbscript.dll 10.0.26100）会报「语句未结束」；仓库里的 ASP 代码也从不用
 *      这种写法，所以既有的 cscript 编译门禁一直没暴露它。
 *   2) 不能用 `;` 作语句分隔符（VBScript 只认 `:`），一律换行。
 * 另外整行注释已剥离、脚本是纯 ASCII，用 UTF-8 + CRLF 落盘即可
 * （UTF-16LE+BOM 会被本机 cscript 误判）。
 */
const harness = `' generated by tests/visitor-geo-runtime-smoke.mjs
Option Explicit

Dim AppStore
Set AppStore = CreateObject("Scripting.Dictionary")

Function AppGet(ByVal key)
  If AppStore.Exists(key) Then
    AppGet = AppStore.Item(key)
  Else
    Err.Raise 5, "AppGet", "missing"
  End If
End Function

Sub AppSet(ByVal key, ByVal value)
  If AppStore.Exists(key) Then
    AppStore.Item(key) = value
  Else
    AppStore.Add key, value
  End If
End Sub

' 桩的 CreateObject 必须经由全局函数中转：本机 cscript 在 class 作用域里访问不到
' VBScript 引擎对象（报「变量未定义: 'VBScript'」），而 include 里的
' On Error Resume Next 会把这种失败悄悄吞掉 —— 少了这一层，harness 会把
' 「桩创建对象失败」误报成「产品代码不工作」。
Function RealCreateObject(ByVal name)
  Set RealCreateObject = CreateObject(CStr(name))
End Function

Class FakeRequest
  Public RemoteAddress
  Public Function ServerVariables(ByVal name)
    If LCase(CStr(name)) = "remote_addr" Then
      ServerVariables = RemoteAddress
    Else
      ServerVariables = ""
    End If
  End Function
End Class

Class FakeServer
  Public ConfigPath
  Public Function MapPath(ByVal relative)
    MapPath = ConfigPath
  End Function
  Public Function URLEncode(ByVal value)
    URLEncode = CStr(value)
  End Function
  Public Function CreateObject(ByVal name)
    Set CreateObject = RealCreateObject(name)
  End Function
End Class

Dim Server
Dim Request
Dim Report
Set Server = New FakeServer
Set Request = New FakeRequest
Server.ConfigPath = "${configPath.replace(/\\/g, "\\\\")}"
Request.RemoteAddress = "59.137.225.151"
Report = ""

Function Say(ByVal key, ByVal value)
  Report = Report & key & "=" & value & vbCrLf
End Function

${helpers}

${asciiCode}

GeoConfigureSub Server.MapPath("visitor-analytics.config.asp")
Dim probeFso
Set probeFso = Server.CreateObject("Scripting.FileSystemObject")
Say "probe_path", GeoConfigPath
Say "probe_exists", CStr(probeFso.FileExists(GeoConfigPath))
Set probeFso = Nothing
Say "safe_ipv4", GeoSafeAddress("59.137.225.151")
Dim q
q = Chr(34)
Dim sampleJson
sampleJson = "{" & q & "ip" & q & ": " & q & "59.137.225.151" & q & ", " & q & "success" & q & ": true, " & _
  q & "country_code" & q & ": " & q & "JP" & q & ", " & q & "country" & q & ": " & q & "Japan" & q & ", " & _
  q & "region" & q & ": " & q & "Tokyo" & q & ", " & q & "city" & q & ": " & q & "Tokyo" & q & "}"
Say "field_cc", GeoJsonFieldValue(sampleJson, "country_code|countryCode|code", 8)
Say "field_country", GeoJsonFieldValue(sampleJson, "country|country_name|countryName", 80)
Say "field_city", GeoJsonFieldValue(sampleJson, "city|city_name|cityName|district", 120)
Say "safe_ipv6", GeoSafeAddress("2001:4860:4860::8888")
Say "safe_garbage", CStr(GeoSafeAddress("abc"))
Say "public_ipv4", CStr(GeoIsPublicAddress("59.137.225.151"))
Say "public_private", CStr(GeoIsPublicAddress("192.168.1.1"))
Say "public_172_16", CStr(GeoIsPublicAddress("172.16.0.1"))
Say "public_172_32", CStr(GeoIsPublicAddress("172.32.0.1"))
Say "config_loaded", CStr(GeoLoadApiConfig())
Say "config_base", GeoApiBase
Say "config_cap", CStr(GeoDailyCap)
Say "external_configured", CStr(GeoExternalConfigured())
Say "endpoint_count", CStr(GeoApiEndpointCount())

GeoResetDebug
GeoDiagnoseSelf
Say "diagnose_log", Replace(Replace(GeoDebugLog, vbCrLf, " "), vbLf, " ")
Say "failure_summary", GeoFailureSummary()

GeoResetDebug
GeoResetResult
GeoResolve "59.137.225.151"
Say "resolve_by", GeoResolvedBy
Say "resolve_log", Replace(Replace(GeoDebugLog, vbCrLf, " "), vbLf, " ")

GeoResetDebug
GeoResetResult
GeoResolve "192.168.1.1"
Say "resolve_private_log", Replace(Replace(GeoDebugLog, vbCrLf, " "), vbLf, " ")

' 总时长上限必须真的生效：把预算设成 0，一个端点都不该发起
' （逐端点 2.5-3s 超时叠加起来会让访客等 8 秒以上）。
GeoTotalBudgetMs = 0
GeoResetDebug
GeoResetResult
GeoResolve "8.8.8.8"
Say "budget_capped_log", Replace(Replace(GeoDebugLog, vbCrLf, " "), vbLf, " ")
Say "budget_capped_by", GeoResolvedBy
GeoTotalBudgetMs = 4000

Say "budget_remaining", CStr(GeoApiBudgetRemaining())

GeoResetDebug
Say "cooldown_first", CStr(GeoAddressOnCooldown("203.0.113.77"))
GeoAddressTouched "203.0.113.77"
Say "cooldown_after_touch", CStr(GeoAddressOnCooldown("203.0.113.77"))
Say "cooldown_other", CStr(GeoAddressOnCooldown("203.0.113.78"))
GeoSkipAddress "10.0.0.9"
Say "day_key", GeoDayKey("webwindows_geo_repair_")
WScript.Echo Report
`;

const scriptPath = path.join(scratch, "geo-runtime.vbs");
// cscript 要求 CRLF 行尾；脚本已剥离注释、纯 ASCII，用最朴素编码即可。
writeFileSync(scriptPath, harness.replace(/\r?\n/g, "\r\n"), "utf8");

let stdout = "";
let failed = false;
try {
  stdout = execFileSync("cscript.exe", ["//nologo", scriptPath], {
    encoding: "utf8",
    timeout: 180000,
    maxBuffer: 8 << 20,
    windowsHide: true
  });
} catch (error) {
  failed = true;
  stdout = `${error.stdout || ""}\n${error.stderr || ""}`.trim() || "(no output)";
  stdout += `\n(harness kept at ${scriptPath})`;
}

assert.ok(!failed, `the geo runtime harness must execute cleanly:\n${stdout}`);

if (!process.env.WW_GEO_KEEP_HARNESS) rmSync(scratch, { recursive: true, force: true });

const values = new Map();
for (const line of stdout.split(/\r?\n/)) {
  const at = line.indexOf("=");
  if (at > 0) values.set(line.slice(0, at).trim(), line.slice(at + 1).trim());
}

assert.equal(values.get("safe_ipv4"), "59.137.225.151", "an IPv4 address must survive the whitelist");
assert.equal(values.get("safe_ipv6"), "2001:4860:4860::8888", "an IPv6 address must survive the whitelist");
assert.equal(values.get("safe_garbage"), "", "garbage text must be rejected");
assert.equal(values.get("public_ipv4"), "True");
assert.equal(values.get("public_private"), "False");
assert.equal(values.get("public_172_16"), "False");
assert.equal(values.get("public_172_32"), "True");
assert.equal(values.get("config_loaded"), "True", "the configured file must load");
assert.equal(values.get("config_base"), "https://ipwho.is/{IP}?lang=zh-CN");
assert.equal(values.get("config_cap"), "800");
assert.equal(values.get("external_configured"), "True");
assert.equal(values.get("endpoint_count"), "1");

// 字段解析是这里最容易静默失效的一环（正则少一个引号就永远取不到值），用固定样本钉死。
assert.equal(values.get("field_cc"), "JP", "country_code must be extracted from a provider response");
assert.equal(values.get("field_country"), "Japan", "country must be extracted from a provider response");
assert.equal(values.get("field_city"), "Tokyo", "city must be extracted from a provider response");

// 诊断必须至少记录「客户端地址 + 端点尝试」两条，否则等于没跑
const diagnoseLog = values.get("diagnose_log") || "";
assert.ok(diagnoseLog.includes("59.137.225.151"), `diagnose must report the client address: ${diagnoseLog}`);
assert.ok(/no-client-address|private-address-not-sent|geo-not-configured|http-error|ok /.test(diagnoseLog),
  `diagnose must reach the endpoint stage: ${diagnoseLog}`);
assert.ok(!diagnoseLog.includes("no-client-address"),
  `the address must not be rejected as a client address: ${diagnoseLog}`);

assert.equal(values.get("cooldown_first"), "False", "an address that was never tried must not be on cooldown");
assert.equal(values.get("cooldown_after_touch"), "True", "a just-attempted address must go on cooldown");
assert.equal(values.get("cooldown_other"), "False", "cooldown must be per address, not global");
assert.match(values.get("day_key") || "", /^webwindows_geo_repair_\d{4}_\d{2}_\d{2}$/);

// 总时长上限：预算为 0 时必须一个端点都不发起（否则访客要等 2.5-3s × 端点数）
assert.equal((values.get("budget_capped_log") || "").replace(/[[\]]/g, ""), "",
  `no provider request may be attempted once the total time budget is spent: ${values.get("budget_capped_log")}`);
assert.notEqual(values.get("budget_capped_by"), "external-api",
  "a capped resolve must not report a provider result");

// 失败摘要必须能从真实日志里读出「哪个端点、什么状态、多久」——
// 管理端只拿到一个失败计数的话，等于让人猜。
const failureSummary = values.get("failure_summary") || "";
assert.match(failureSummary, /^(外部解析未返回可识别的地区|[^;]*\d+\/\d+ms)/,
  `GeoFailureSummary must summarise the endpoint attempts: ${failureSummary}`);
assert.ok(!/stage-|"client"|"result"/.test(failureSummary),
  `the summary must only list endpoint attempts: ${failureSummary}`);

// 解析必须真的发起了 HTTP：解析来源要么拿到结果，要么在日志里留下失败痕迹
const resolveLog = values.get("resolve_log") || "";
const resolveBy = values.get("resolve_by");
assert.ok(resolveBy === "external-api" || /http-error|empty-body|unparsed-body|client-create-failed/.test(resolveLog),
  `GeoResolve must attempt the provider: by=${resolveBy} log=${resolveLog}`);

const privateLog = values.get("resolve_private_log") || "";
assert.ok(!/endpoint/.test(privateLog.replace(/private/g, "")),
  `private addresses must never be sent to a provider: ${privateLog}`);

assert.ok(Number(values.get("budget_remaining")) >= 0, "remaining budget must be a number");

console.log(`visitor geo runtime smoke test passed: resolveBy=${resolveBy} diagnose=[${diagnoseLog}]`);
