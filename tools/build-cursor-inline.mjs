// Keep cursor pixels available before any external image request completes.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const root = fileURLToPath(new URL('../assets/cursors/', import.meta.url));
const output = fileURLToPath(new URL('../assets/js/cursor-theme-inline.js', import.meta.url));
const themes = ['dreama', 'classic', 'soft', 'dark-pro', 'mono'];
const states = [
  'default', 'pointer', 'text', 'wait', 'progress', 'move', 'not-allowed',
  'crosshair', 'help', 'ew-resize', 'ns-resize', 'nwse-resize', 'nesw-resize'
];
const images = {};
for (const theme of themes) {
  images[theme] = {};
  for (const state of states) {
    images[theme][state] = (await readFile(join(root, theme, `${state}.png`))).toString('base64');
  }
}
await writeFile(output, `// Generated by tools/build-cursor-inline.mjs from assets/cursors/*/*.png.\nwindow.WebWindowsCursorImages = ${JSON.stringify(images)};\n`);
console.log(`Embedded ${themes.length * states.length} cursor images`);
